// Shared e2e fixtures. The toolbar click cannot be simulated, so each worker tests a
// throwaway COPY of the extension whose background.js wraps the real one and adds a
// test-only 'ww-test-run' message. The repo's own background.js is never modified.
const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');
const base = require('@playwright/test');

const { chromium, expect } = base;
const ROOT = path.resolve(__dirname, '..');
const NOT_EXTENSION = new Set(['playwright.config.js']);

const HARNESS = `// Generated by e2e/fixtures.js. Test-only wrapper around the real service worker.
importScripts('background.original.js');

let lastNotify = '';
const originalNotify = notify;
notify = (message) => {
  lastNotify = String(message);
  originalNotify(message);
};

// Playwright saves downloads under a random name, so record the filename the extension asked for.
self.__downloadRequests = [];
const originalDownload = chrome.downloads.download.bind(chrome.downloads);
chrome.downloads.download = (options) => {
  self.__downloadRequests.push(options.filename);
  return originalDownload(options);
};

chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
  if (!msg || msg.type !== 'ww-test-run') return false;
  lastNotify = '';
  chrome.tabs
    .query({ url: msg.url })
    .then((tabs) => {
      if (!tabs.length) throw new Error('no tab with url ' + msg.url);
      return run(tabs[0]);
    })
    .then(
      () => sendResponse({ ok: true, notification: lastNotify }),
      (err) => sendResponse({ ok: false, error: String((err && err.message) || err) })
    );
  return true;
});
`;

function buildExtensionCopy() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ww-ext-'));
  for (const name of fs.readdirSync(ROOT)) {
    const src = path.join(ROOT, name);
    const isDir = fs.statSync(src).isDirectory();
    const wanted = isDir ? name === 'icons' || name === 'lib' : name === 'manifest.json' || /\.(js|html)$/.test(name);
    if (!wanted || NOT_EXTENSION.has(name)) continue;
    fs.cpSync(src, path.join(dir, name), { recursive: true });
  }
  fs.renameSync(path.join(dir, 'background.js'), path.join(dir, 'background.original.js'));
  fs.writeFileSync(path.join(dir, 'background.js'), HARNESS);
  return dir;
}

// Varied filler: Readability scores repeated identical text poorly.
function filler(n) {
  return Array.from(
    { length: n },
    (_, i) =>
      `<p>Paragraph ${i}: Readability wants reasonably long text, with commas, clauses, and several sentences to score it as real content.</p>`
  ).join('');
}

function page(title, marker, extra) {
  return `<!doctype html><html><head><title>${title}</title></head><body>
${(extra && extra.before) || ''}<article><h1>${title}</h1><p>${marker}</p>${filler(8)}</article>${(extra && extra.after) || ''}
</body></html>`;
}

const MARKERS = {
  one: 'WW marker sentence number one.',
  two: 'WW marker sentence number two.',
  nav: 'WW marker sentence for the navigation page.'
};

const PAGES = {
  '/one': page('WW Page One', MARKERS.one),
  '/two': page('WW Page Two', MARKERS.two),
  '/nav': page('WW Nav Page', MARKERS.nav, {
    before: '<nav><ul><li><a href="/x">NAVTEXT-MENU-ITEM</a></li><li><a href="/y">NAVTEXT-OTHER</a></li></ul></nav>',
    after: '<footer><p>FOOTERTEXT-COPYRIGHT</p></footer>'
  })
};

const test = base.test.extend({
  extDir: [
    // eslint-disable-next-line no-empty-pattern
    async ({}, use) => {
      const dir = buildExtensionCopy();
      await use(dir);
      fs.rmSync(dir, { recursive: true, force: true });
    },
    { scope: 'worker' }
  ],

  site: [
    // eslint-disable-next-line no-empty-pattern
    async ({}, use) => {
      const server = http.createServer((req, res) => {
        const body = PAGES[req.url.split('?')[0]];
        res.writeHead(body ? 200 : 404, { 'content-type': 'text/html; charset=utf-8' });
        res.end(body || 'not found');
      });
      await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
      const origin = `http://127.0.0.1:${server.address().port}`;
      await use({ origin, url: (p) => origin + p });
      await new Promise((resolve) => server.close(resolve));
    },
    { scope: 'worker' }
  ],

  ext: async ({ extDir, site }, use) => {
    const context = await chromium.launchPersistentContext('', {
      headless: false,
      args: [`--disable-extensions-except=${extDir}`, `--load-extension=${extDir}`]
    });
    let [worker] = context.serviceWorkers();
    if (!worker) worker = await context.waitForEvent('serviceworker');
    const extensionId = worker.url().split('/')[2];
    await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: site.origin });

    const controller = await context.newPage();
    await controller.goto(`chrome-extension://${extensionId}/options.html`);

    const api = {
      context,
      worker,
      async setSettings(settings) {
        await worker.evaluate(async (s) => {
          await chrome.storage.sync.clear();
          await chrome.storage.sync.set(s);
        }, settings);
      },
      async open(pathname) {
        const p = await context.newPage();
        await p.goto(site.url(pathname));
        return p;
      },
      // Runs the extension's save for the tab showing `url`. Returns { ok, notification }.
      // Pass { focus: false } to keep a multi-tab selection (activating a tab resets it).
      async run(p, { focus = true } = {}) {
        if (focus) await p.bringToFront();
        const reply = await controller.evaluate(
          (url) => chrome.runtime.sendMessage({ type: 'ww-test-run', url }),
          p.url()
        );
        expect(reply.ok, reply.error).toBe(true);
        return reply.notification;
      },
      async setClipboard(p, text) {
        await p.bringToFront();
        await p.evaluate((t) => navigator.clipboard.writeText(t), text);
      },
      async readClipboard(p) {
        await p.bringToFront();
        // Windows returns CRLF line endings; normalise so tests compare plain \n.
        const text = await p.evaluate(() => navigator.clipboard.readText());
        return text.replace(/\r\n/g, '\n');
      },
      // Completed downloads, oldest first, as { requested, filename }.
      // requested: name the extension asked for. filename: where Playwright stored the bytes.
      async downloads() {
        return worker.evaluate(async () => {
          const items = await chrome.downloads.search({ orderBy: ['startTime'] });
          return items
            .filter((d) => d.state === 'complete')
            .map((d, i) => ({ requested: self.__downloadRequests[i], filename: d.filename }));
        });
      },
      async waitForDownloads(count) {
        await expect.poll(async () => (await api.downloads()).length, { timeout: 15000 }).toBeGreaterThanOrEqual(count);
        return api.downloads();
      }
    };

    await use(api);
    await context.close();
  }
});

module.exports = { test, expect, MARKERS };
