// Small file whose header claims 30000 x 30000 pixels.
const HUGE_DIMENSIONS_PNG = Buffer.from(makePng(1, 1));
HUGE_DIMENSIONS_PNG.writeUInt32BE(30000, 16);
HUGE_DIMENSIONS_PNG.writeUInt32BE(30000, 20);

const test = base.test.extend({
  extDir: [
    // eslint-disable-next-line no-empty-pattern
    async ({}, use) => {
      const dir = buildExtensionCopy();
      await use(dir);
      fs.rmSync(dir, { recursive: true, force: true });
    },
    { scope: 'worker' }
  ],

  site: [
    // eslint-disable-next-line no-empty-pattern
    async ({}, use) => {
      const requests = [];
      let origin = '';
      const server = http.createServer((req, res) => {
        requests.push(req.url);
        const route = req.url.split('?')[0];
        if (route === '/big.png') {
          res.writeHead(200, { 'content-type': 'image/png', 'content-length': BIG_PNG.length });
          res.end(BIG_PNG);
          return;
        }
        if (route === '/redirect.png') {
          res.writeHead(302, { location: '/big.png?from=redirect' });
          res.end();
          return;
        }
        if (route === '/vector.svg') {
          res.writeHead(200, { 'content-type': 'image/svg+xml' });
          res.end('<svg xmlns="http://www.w3.org/2000/svg" width="100000" height="100000"><rect width="100%" height="100%"/></svg>');
          return;
        }
        if (route === '/huge-dimensions.png') {
          res.writeHead(200, { 'content-type': 'image/png' });
          res.end(HUGE_DIMENSIONS_PNG);
          return;
        }
        // A body that never ends, with no declared size.
        if (route === '/endless.png') {
          res.writeHead(200, { 'content-type': 'image/png' });
          const timer = setInterval(() => res.write(Buffer.alloc(1024)), 200);
          req.on('close', () => clearInterval(timer));
          return;
        }
        // Over the byte limit, sent without a declared size so the streaming check is what stops it.
        if (route === '/huge.png') {
          res.writeHead(200, { 'content-type': 'image/png' });
          const chunk = Buffer.alloc(1024 * 1024);
          let sent = 0;
          const pump = () => {
            while (sent < 64 && !res.destroyed) {
              sent += 1;
              if (!res.write(chunk)) return res.once('drain', pump);
            }
            res.end();
          };
          pump();
          return;
        }
        const body = PAGES[route];
        res.writeHead(body ? 200 : 404, { 'content-type': 'text/html; charset=utf-8' });
        res.end(body ? body.replace(/__ORIGIN__/g, origin) : 'not found');
      });
      await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
      origin = `http://127.0.0.1:${server.address().port}`;
      await use({ origin, requests, url: (p) => origin + p });
      server.closeAllConnections();
      await new Promise((resolve) => server.close(resolve));
    },
    { scope: 'worker' }
  ],

  ext: async ({ extDir, site }, use) => {
    const context = await chromium.launchPersistentContext('', {
      headless: false,
      args: [`--disable-extensions-except=${extDir}`, `--load-extension=${extDir}`]
    });
    let [worker] = context.serviceWorkers();
    if (!worker) worker = await context.waitForEvent('serviceworker');
    const extensionId = worker.url().split('/')[2];
    await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: site.origin });

    const controller = await context.newPage();
    await controller.goto(`chrome-extension://${extensionId}/options.html`);

    const api = {
      context,
      worker,
      async setSettings(settings) {
        await worker.evaluate(async (s) => {
          await chrome.storage.local.clear();
          await chrome.storage.local.set(s);
        }, settings);
      },
      async open(pathname) {
        const p = await context.newPage();
        await p.goto(site.url(pathname));
        return p;
      },
      // Runs the extension's save for the tab showing `url`. Returns { ok, notification }.
      // Pass { focus: false } to keep a multi-tab selection (activating a tab resets it).
      async run(p, { focus = true } = {}) {
        if (focus) await p.bringToFront();
        const reply = await controller.evaluate(
          (url) => chrome.runtime.sendMessage({ type: 'ww-test-run', url }),
          p.url()
        );
        expect(reply.ok, reply.error).toBe(true);
        return reply.notification;
      },
      async setClipboard(p, text) {
        await p.bringToFront();
        await p.evaluate((t) => navigator.clipboard.writeText(t), text);
      },
      async readClipboard(p) {
        await p.bringToFront();
        // Windows returns CRLF line endings; normalise so tests compare plain \n.
        const text = await p.evaluate(() => navigator.clipboard.readText());
        return text.replace(/\r\n/g, '\n');
      },
      // Completed downloads, oldest first, as { requested, filename }.
      // requested: name the extension asked for. filename: where Playwright stored the bytes.
      async downloads() {
        return worker.evaluate(async () => {
          const items = await chrome.downloads.search({ orderBy: ['startTime'] });
          return items
            .filter((d) => d.state === 'complete')
            .map((d, i) => ({ requested: self.__downloadRequests[i], filename: d.filename }));
        });
      },
      async waitForDownloads(count) {
        await expect.poll(async () => (await api.downloads()).length, { timeout: 15000 }).toBeGreaterThanOrEqual(count);
        return api.downloads();
      }
    };

    await use(api);
    await context.close();
  }
});

