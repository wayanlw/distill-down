// Shared e2e fixtures. The toolbar click cannot be simulated, so each worker tests a
// throwaway COPY of the extension whose background.js wraps the real one and adds a
// test-only 'ww-test-run' message. The repo's own background.js is never modified.
const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');
const base = require('@playwright/test');

const { chromium, expect } = base;
const ROOT = path.resolve(__dirname, '..');
const NOT_EXTENSION = new Set(['playwright.config.js']);

const HARNESS = `// Generated by e2e/fixtures.js. Test-only wrapper around the real service worker.
importScripts('background.original.js');

let lastNotify = '';
const originalNotify = notify;
notify = (message) => {
  lastNotify = String(message);
  originalNotify(message);
};

// Playwright saves downloads under a random name, so record the filename the extension asked for.
self.__downloadRequests = [];
const originalDownload = chrome.downloads.download.bind(chrome.downloads);
chrome.downloads.download = (options) => {
  self.__downloadRequests.push(options.filename);
  return originalDownload(options);
};

// Count decode requests. Set self.__hangEncodes to n to make the next n never answer.
self.__encodeCount = 0;
self.__hangEncodes = 0;
self.__offscreenCloses = 0;
const originalOffscreenMessage = offscreenMessage;
offscreenMessage = (msg) => {
  if (msg.type === 'encodeImage') {
    self.__encodeCount += 1;
    if (self.__hangEncodes > 0) {
      self.__hangEncodes -= 1;
      return new Promise(() => {});
    }
  }
  return originalOffscreenMessage(msg);
};
const originalClose = chrome.offscreen.closeDocument.bind(chrome.offscreen);
chrome.offscreen.closeDocument = () => {
  self.__offscreenCloses += 1;
  return originalClose();
};

// Set self.__failDownloads to make every download report as interrupted.
const originalSearch = chrome.downloads.search.bind(chrome.downloads);
chrome.downloads.search = (query) =>
  self.__failDownloads ? Promise.resolve([{ state: 'interrupted', error: 'USER_CANCELED' }]) : originalSearch(query);

chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
  if (!msg || msg.type !== 'ww-test-run') return false;
  lastNotify = '';
  chrome.tabs
    .query({ url: msg.url })
    .then((tabs) => {
      if (!tabs.length) throw new Error('no tab with url ' + msg.url);
      return run(tabs[0]);
    })
    .then(
      () => sendResponse({ ok: true, notification: lastNotify }),
      (err) => sendResponse({ ok: false, error: String((err && err.message) || err) })
    );
  return true;
});
`;

function buildExtensionCopy() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ww-ext-'));
  for (const name of fs.readdirSync(ROOT)) {
    const src = path.join(ROOT, name);
    const isDir = fs.statSync(src).isDirectory();
    const wanted = isDir ? name === 'icons' || name === 'lib' : name === 'manifest.json' || /\.(js|html)$/.test(name);
    if (!wanted || NOT_EXTENSION.has(name)) continue;
    fs.cpSync(src, path.join(dir, name), { recursive: true });
  }
  // Playwright cannot click Chrome's permission prompt, so the copy declares the optional
  // "debugger" permission as granted. The repo's manifest keeps it optional.
  const mpath = path.join(dir, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(mpath, 'utf8'));
  manifest.permissions = manifest.permissions.concat(manifest.optional_permissions || []);
  delete manifest.optional_permissions;
  fs.writeFileSync(mpath, JSON.stringify(manifest, null, 2));
  fs.renameSync(path.join(dir, 'background.js'), path.join(dir, 'background.original.js'));
  fs.writeFileSync(path.join(dir, 'background.js'), HARNESS);
  return dir;
}

// Varied filler: Readability scores repeated identical text poorly.
function filler(n) {
  return Array.from(
    { length: n },
    (_, i) =>
      `<p>Paragraph ${i}: Readability wants reasonably long text, with commas, clauses, and several sentences to score it as real content.</p>`
  ).join('');
}

function page(title, marker, extra) {
  return `<!doctype html><html><head><title>${title}</title></head><body>
${(extra && extra.before) || ''}<article><h1>${title}</h1><p>${marker}</p>${filler(8)}${(extra && extra.inside) || ''}</article>${(extra && extra.after) || ''}
</body></html>`;
}

// Dependency-free RGB PNG (gradient). Wider than the 1000 px the extension downscales to.
function makePng(width, height) {
  const zlib = require('zlib');
  const chunk = (type, data) => {
    const head = Buffer.alloc(4);
    head.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(zlib.crc32(body));
    return Buffer.concat([head, body, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // RGB
  const raw = Buffer.alloc((width * 3 + 1) * height);
  let o = 0;
  for (let y = 0; y < height; y++) {
    raw[o++] = 0; // filter: none
    for (let x = 0; x < width; x++) {
      raw[o++] = x % 256;
      raw[o++] = y % 256;
      raw[o++] = (x + y) % 256;
    }
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0))
  ]);
}

